package com.riksa.social.service;

import com.riksa.auth.entity.User;
import com.riksa.auth.repository.UserRepository;
import com.riksa.auth.security.RateLimitDecision;
import com.riksa.auth.security.RedisRateLimiter;
import com.riksa.common.exception.RateLimitExceededException;
import com.riksa.common.exception.ServiceUnavailableException;
import com.riksa.social.entity.Category;
import com.riksa.social.entity.UserCategoryMembership;
import com.riksa.social.repository.CategoryRepository;
import com.riksa.social.repository.UserCategoryMembershipRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.security.SecureRandom;
import java.text.Normalizer;
import java.time.Duration;
import java.util.HexFormat;
import java.util.Locale;
import java.util.Set;
import java.util.UUID;
import java.util.regex.Pattern;

/**
 * Lets members found their own communities.
 *
 * <p>Anything a learner types here is shown to every other learner, so the
 * rules are strict: only verified accounts in good standing may create, each
 * account has a daily and a lifetime quota, names are cleaned and checked
 * against impersonation, and the slug is always generated by the server.
 */
@Service
@RequiredArgsConstructor
public class CommunityCreationService {

    static final int NAME_MIN = 3;
    static final int NAME_MAX = 50;
    static final int DESCRIPTION_MAX = 300;
    static final int MAX_OWNED = 5;
    static final int DAILY_LIMIT = 3;
    private static final int SLUG_BASE_MAX = 60;
    private static final Duration DAILY_WINDOW = Duration.ofDays(1);

    /** Letters and marks of any script (Khmer included), digits, and a little punctuation. */
    private static final Pattern NAME_PATTERN = Pattern.compile("[\\p{L}\\p{M}\\p{N} &'.,()+#-]+");
    /** Control, zero-width and bidi-override characters can disguise a name. */
    private static final Pattern HIDDEN_CHARACTERS = Pattern.compile("[\\p{Cc}\\p{Cf}\\p{Co}\\p{Cn}]");
    private static final Pattern HIDDEN_EXCEPT_NEWLINE = Pattern.compile("[\\p{Cc}\\p{Cf}\\p{Co}\\p{Cn}&&[^\\n]]");
    private static final Pattern WHITESPACE = Pattern.compile("\\s+");
    private static final Pattern NON_SLUG = Pattern.compile("[^a-z0-9]+");

    /** Names that would pass for staff or the platform itself, compared without spaces or punctuation. */
    private static final Set<String> RESERVED = Set.of(
            "admin", "administrator", "moderator", "moderators", "mod", "mods", "staff", "support",
            "system", "official", "help", "helpdesk", "root", "security", "teacher", "teachers",
            "null", "undefined", "api", "graphql", "communities", "community", "settings");

    private static final SecureRandom RANDOM = new SecureRandom();

    private final CategoryRepository categoryRepository;
    private final UserCategoryMembershipRepository membershipRepository;
    private final UserRepository userRepository;
    private final MediaUrlValidator mediaUrlValidator;
    private final RedisRateLimiter rateLimiter;

    @Transactional
    public Category create(UUID userId, String rawName, String rawDescription, String rawIconUrl) {
        User user = requireCreator(userId);

        String name = normalizeName(rawName);
        String description = normalizeDescription(rawDescription);
        String iconUrl = normalizeIconUrl(rawIconUrl);

        if (categoryRepository.countByCreatedBy(user.getId()) >= MAX_OWNED) {
            throw new IllegalStateException(
                    "You can own at most " + MAX_OWNED + " communities");
        }
        if (categoryRepository.existsByNameIgnoreCase(name)) {
            throw new IllegalArgumentException("A community with this name already exists");
        }

        // Counted only once the request is otherwise valid, so a typo does not
        // cost the learner one of their daily attempts.
        acquireDailyQuota(user.getId());

        Category category = new Category();
        category.setName(name);
        category.setSlug(uniqueSlug(name));
        category.setDescription(description);
        category.setIconUrl(iconUrl);
        category.setOfficial(false);
        category.setCreatedBy(user.getId());

        Category saved;
        try {
            saved = categoryRepository.saveAndFlush(category);
        } catch (DataIntegrityViolationException e) {
            // Another request took the name (or slug) between the check and the insert.
            throw new IllegalArgumentException("A community with this name already exists");
        }

        // The founder is the first member; posting requires membership.
        UserCategoryMembership membership = new UserCategoryMembership();
        membership.setUserId(user.getId());
        membership.setCategoryId(saved.getId());
        membershipRepository.save(membership);

        return saved;
    }

    private User requireCreator(UUID userId) {
        if (userId == null) {
            throw new AccessDeniedException("Sign in to create a community");
        }
        User user = userRepository.findById(userId)
                .orElseThrow(() -> new AccessDeniedException("Sign in to create a community"));
        if (user.isSuspended()) {
            throw new AccessDeniedException("Suspended accounts cannot create communities");
        }
        if (!isVerified(user)) {
            throw new AccessDeniedException("Verify your account before creating a community");
        }
        return user;
    }

    /** A sign-in through Google or Telegram proves the identity as well as a code does. */
    private static boolean isVerified(User user) {
        return Boolean.TRUE.equals(user.getEmailVerified())
                || Boolean.TRUE.equals(user.getPhoneVerified())
                || user.getTelegramId() != null
                || user.getGoogleId() != null;
    }

    static String normalizeName(String raw) {
        if (raw == null) {
            throw new IllegalArgumentException("Community name is required");
        }
        String name = Normalizer.normalize(raw, Normalizer.Form.NFC);
        if (HIDDEN_CHARACTERS.matcher(name.replaceAll("[\\t\\n\\r]", " ")).find()) {
            throw new IllegalArgumentException("Community name contains characters that are not allowed");
        }
        name = WHITESPACE.matcher(name.strip()).replaceAll(" ");

        int length = name.codePointCount(0, name.length());
        if (length < NAME_MIN || length > NAME_MAX) {
            throw new IllegalArgumentException(
                    "Community name must be " + NAME_MIN + " to " + NAME_MAX + " characters");
        }
        if (!NAME_PATTERN.matcher(name).matches()) {
            throw new IllegalArgumentException(
                    "Community name can only use letters, numbers, spaces and & ' . , ( ) + # -");
        }
        if (name.codePoints().noneMatch(Character::isLetter)) {
            throw new IllegalArgumentException("Community name must contain letters");
        }

        String compact = name.toLowerCase(Locale.ROOT).replaceAll("[^\\p{L}\\p{N}]", "");
        if (RESERVED.contains(compact) || compact.contains("riksa")) {
            throw new IllegalArgumentException("This community name is reserved");
        }
        return name;
    }

    static String normalizeDescription(String raw) {
        if (raw == null || raw.isBlank()) {
            return null;
        }
        String description = Normalizer.normalize(raw, Normalizer.Form.NFC)
                .replace("\r\n", "\n")
                .replace('\r', '\n')
                .replace('\t', ' ')
                .strip();
        if (HIDDEN_EXCEPT_NEWLINE.matcher(description).find()) {
            throw new IllegalArgumentException("Description contains characters that are not allowed");
        }
        // Keep at most one blank line so a description cannot push the page around.
        description = description.replaceAll("\\n{3,}", "\n\n");
        if (description.codePointCount(0, description.length()) > DESCRIPTION_MAX) {
            throw new IllegalArgumentException(
                    "Description must be at most " + DESCRIPTION_MAX + " characters");
        }
        return description;
    }

    private String normalizeIconUrl(String raw) {
        String url = mediaUrlValidator.normalize(raw);
        if (url != null && !url.regionMatches(true, 0, "https://", 0, 8)) {
            throw new IllegalArgumentException("Community icon must use https");
        }
        return url;
    }

    private void acquireDailyQuota(UUID userId) {
        RateLimitDecision decision;
        try {
            decision = rateLimiter.acquire(
                    "community-create", userId.toString(), DAILY_LIMIT, DAILY_WINDOW);
        } catch (RuntimeException e) {
            // Fail closed: without the limiter nothing stops a flood of communities.
            throw new ServiceUnavailableException(
                    "Creating communities is temporarily unavailable", e);
        }
        if (!decision.allowed()) {
            throw new RateLimitExceededException(
                    "You can create at most " + DAILY_LIMIT + " communities a day. Try again later.",
                    decision.retryAfterSeconds());
        }
    }

    /**
     * An ASCII slug from the name, or "community" for names in other scripts,
     * with a random suffix whenever the plain form is taken or reserved.
     */
    String uniqueSlug(String name) {
        String ascii = Normalizer.normalize(name, Normalizer.Form.NFD)
                .replaceAll("\\p{M}", "")
                .toLowerCase(Locale.ROOT);
        String base = NON_SLUG.matcher(ascii).replaceAll("-").replaceAll("(^-+|-+$)", "");
        if (base.length() > SLUG_BASE_MAX) {
            base = base.substring(0, SLUG_BASE_MAX).replaceAll("-+$", "");
        }
        if (base.isEmpty()) {
            base = "community";
        }

        String candidate = base;
        for (int attempt = 0; attempt < 8; attempt++) {
            if (!RESERVED.contains(candidate) && !categoryRepository.existsBySlug(candidate)) {
                return candidate;
            }
            byte[] suffix = new byte[3];
            RANDOM.nextBytes(suffix);
            candidate = base + "-" + HexFormat.of().formatHex(suffix);
        }
        throw new IllegalStateException("Could not choose an address for this community. Try again.");
    }
}
